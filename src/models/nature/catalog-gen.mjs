// Dev helper: regenerates src/catalog/nature.js from the nature modules' VARIANTS / TRIMS
// exports so the static catalog never drifts from the code.  node src/models/nature/catalog-gen.mjs
import { writeFileSync } from 'node:fs';
import * as N from '../nature.js';

const META = [
  ['tree', 'trees', 'Tree', 'createTree', 'TREE_VARIANTS', 'TREE_TRIMS', { seed: 'number/string: every seed grows a different tree', leafColor: 'color', barkColor: 'color', height: 'approx metres' }],
  ['cactus', 'desert', 'Cactus', 'createCactus', 'CACTUS_VARIANTS', 'CACTUS_TRIMS', { color: 'body color', seed: 'number' }],
  ['succulent', 'desert', 'Succulent', 'createSucculent', 'SUCCULENT_VARIANTS', 'SUCCULENT_TRIMS', { color: 'leaf color', seed: 'number' }],
  ['bush', 'shrubs', 'Bush', 'createBush', 'BUSH_VARIANTS', 'BUSH_TRIMS', { color: 'leaf color', flowerColor: 'flower color', size: 'scale', seed: 'number' }],
  ['hedge', 'shrubs', 'Hedge', 'createHedge', 'HEDGE_VARIANTS', 'HEDGE_TRIMS', { color: 'leaf color', length: 'm', height: 'm', depth: 'm', seed: 'number' }],
  ['flower', 'flowers', 'Flower', 'createFlower', 'FLOWER_VARIANTS', 'FLOWER_TRIMS', { color: 'petal color', seed: 'number' }],
  ['grass', 'grass', 'Grass', 'createGrass', 'GRASS_VARIANTS', 'GRASS_TRIMS', { color: 'blade color', seed: 'number' }],
  ['crop', 'crops', 'Crop', 'createCrop', 'CROP_VARIANTS', 'CROP_TRIMS', { color: 'leaf color', seed: 'number' }],
  ['water-plant', 'water', 'Water plant', 'createWaterPlant', 'WATER_PLANT_VARIANTS', 'WATER_PLANT_TRIMS', { color: 'leaf color', flowerColor: 'flower color', seed: 'number' }],
  ['reef', 'water', 'Reef', 'createReef', 'REEF_VARIANTS', 'REEF_TRIMS', { color: 'main color', seed: 'number' }],
  ['vine', 'shrubs', 'Vine', 'createVine', 'VINE_VARIANTS', 'VINE_TRIMS', { color: 'leaf color', flowerColor: 'flower color', seed: 'number' }],
  ['rock', 'rocks', 'Rock', 'createRock', 'ROCK_VARIANTS', 'ROCK_TRIMS', { color: 'stone color', size: 'scale', seed: 'number' }],
  ['mushroom', 'ground', 'Mushroom', 'createMushroom', 'MUSHROOM_VARIANTS', 'MUSHROOM_TRIMS', { color: 'cap color', seed: 'number' }],
  ['log', 'ground', 'Log & stump', 'createLog', 'LOG_VARIANTS', 'LOG_TRIMS', { color: 'bark color', seed: 'number' }],
  ['terrain', 'terrain', 'Terrain', 'createTerrain', 'TERRAIN_VARIANTS', 'TERRAIN_TRIMS', { size: 'tile size in m', seed: 'number' }],
];

const out = {};
for (const [type, sub, label, factory, V, TR, options] of META) {
  if (!N[V]) continue;
  const variants = Object.keys(N[V]);
  const trims = N[TR] ?? {};
  out[type] = { category: 'nature', sub, source: 'js', module: 'nature', factory, label, variants, trims: Object.fromEntries(variants.map((v) => [v, trims[v] ?? []])), options };
}
let s = '// Catalog entries owned by src/models/nature*. Generated by src/models/nature/catalog-gen.mjs — edit the modules, then rerun.\n// trims: extra versions of each variant, named "<variant>-<trim>".\nexport default {\n';
for (const [k, e] of Object.entries(out)) s += `  ${JSON.stringify(k)}: ${JSON.stringify(e)},\n`;
writeFileSync(new URL('../../catalog/nature.js', import.meta.url), s + '};\n');
const total = Object.values(out).reduce((a, e) => a + e.variants.reduce((b, v) => b + 1 + e.trims[v].length, 0), 0);
console.log(`src/catalog/nature.js: ${Object.keys(out).length} types, ${total} models`);
