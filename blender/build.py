"""Build the HD (.glb) models with Blender, headless.

  Blender -b --factory-startup --python blender/build.py -- [--only hd-sofa,hd-rock] [--variant chesterfield]
                                                           [--render] [--catalog-only] [--skip-existing]

Writes hd/models/<type>/<variant>.glb and regenerates src/catalog/hd.js from the registry.
Every model is generated procedurally by the builders in blender/models/*.py (no external assets).
"""
import bpy, sys, os, time, json, importlib, pkgutil, math, traceback

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from lib import core, mats, bake, export, check  # noqa: E402

argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
def arg(name, default=None):
    if name in argv:
        i = argv.index(name)
        return argv[i + 1] if i + 1 < len(argv) and not argv[i + 1].startswith('--') else True
    return default

only = set(filter(None, (arg('--only') or '').split(','))) if arg('--only') else None
only_variant = set(filter(None, (arg('--variant') or '').split(','))) if arg('--variant') else None
render = bool(arg('--render'))
check_only = bool(arg('--check-only'))
skip_existing = bool(arg('--skip-existing'))
render_dir = arg('--render-dir', os.path.join(ROOT, 'blender', '_renders'))

# ---- registry
import models  # noqa: E402
REG = {}
for mi in pkgutil.iter_modules(models.__path__):
    mod = importlib.import_module(f'models.{mi.name}')
    REG.update({k: v for k, v in getattr(mod, 'TYPES', {}).items() if not v.get('disabled') or os.environ.get('HD_EXPERIMENTAL') == '1'})

def built(t, v):
    return os.path.exists(os.path.join(ROOT, 'hd', 'models', t, f'{v}.glb'))

