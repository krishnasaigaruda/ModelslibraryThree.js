def write_catalog():
    """Only variants whose .glb exists (built + passed the connectivity check) are listed."""
    lines = ['// Catalog entries for the Blender-made HD models (hd/models/<type>/<variant>.glb).',
             '// GENERATED by blender/build.py from blender/models/*.py — edit the builders, not this file.',
             '// Every model is procedurally modelled + textured by our own bpy scripts (no third-party assets).',
             'export default {']
    for t in sorted(REG, key=lambda k: (REG[k]['category'], k)):
        e = REG[t]
        variants = [v for v in e['variants'] if built(t, v)]
        if not variants:
            continue
        entry = {'category': e['category']}
        if e.get('sub'): entry['sub'] = e['sub']
        entry.update({'source': 'glb', 'quality': 'hd', 'label': e['label'], 'variants': variants, 'options': e.get('options', {}),
                      'tags': e.get('tags') or TAGS.get(t) or [t[3:].replace('-', ' ')]})
        lines.append(f'  {json.dumps(t)}: {json.dumps(entry)},')
    lines.append('};\n')
    open(os.path.join(ROOT, 'src', 'catalog', 'hd.js'), 'w').write('\n'.join(lines))

def render_preview(path, kind):
    sc = bpy.context.scene
    mn, mx = core.bounds()
    size = max(mx - mn)
    cx, cy, cz = (mn + mx) / 2
    # camera 3/4 front (front = -Y; vehicles front = +X)
    cam_d = bpy.data.cameras.new('cam'); cam_d.lens = 50
    cam = core.link(bpy.data.objects.new('cam', cam_d))
    import mathutils
    dirv = mathutils.Vector((1.0, -1.25, 0.75)) if kind != 'vehicles' else mathutils.Vector((1.4, -1.0, 0.6))
    dirv.normalize()
    cam.location = mathutils.Vector((cx, cy, cz)) + dirv * size * 2.1
    cam.rotation_euler = (mathutils.Vector((cx, cy, cz)) - cam.location).to_track_quat('-Z', 'Y').to_euler()
    sc.camera = cam
    w = bpy.data.worlds.new('w'); sc.world = w; w.use_nodes = True
    w.node_tree.nodes['Background'].inputs[0].default_value = (0.8, 0.82, 0.85, 1)
    w.node_tree.nodes['Background'].inputs[1].default_value = 0.8
    sun_d = bpy.data.lights.new('sun', 'SUN'); sun_d.energy = 3.5; sun_d.angle = 0.2
    sun = core.link(bpy.data.objects.new('sun', sun_d)); sun.rotation_euler = (math.radians(50), 0, math.radians(30))
    floor = core.box('floor', (size * 8, size * 8, 0.01), at=(cx, cy, -0.005))
    floor.data.materials.append(mats.mat('floor_preview', 'flat', color='#d8d6d0', rough=0.9))
    sc.render.engine = 'CYCLES'
    sc.cycles.samples = 24
    sc.cycles.use_denoising = True
    sc.render.resolution_x, sc.render.resolution_y = 480, 360
    sc.render.filepath = path
    bpy.ops.render.render(write_still=True)
    bpy.data.objects.remove(floor); bpy.data.objects.remove(cam); bpy.data.objects.remove(sun)

def build_one(t, v, params):
    core.reset()
    mats.reset_cache()
    e = REG[t]
    e['build'](dict(params))
    core.ground_and_centre(centre=e.get('centre', True))
    mn, mx = core.bounds()
    if max(mx - mn) > e.get('max_dim', 6.0):
        raise RuntimeError(f'model is {max(mx - mn):.1f} m — broken geometry (spike) suspected')
    floating = check.connectivity(core.mesh_objects())
    path = os.path.join(ROOT, 'hd', 'models', t, f'{v}.glb')
    if floating:
        if os.path.exists(path):
            os.remove(path)  # never ship a model with floating parts
        raise RuntimeError(f'floating parts: {", ".join(sorted(set(floating)))}')
    if check_only:
        return 0
    objs = bake.bake_all(max_res=e.get('max_res', 1024))
    core.ground_and_centre(objs, centre=e.get('centre', True))
    for o in objs:
        o.name = o.data.materials[0].name if o.data.materials else o.name
    size = export.export_glb(path, objs)
    if render:
        os.makedirs(render_dir, exist_ok=True)
        render_preview(os.path.join(render_dir, f'{t}-{v}.png'), e['category'])
    return size

if __name__ == '__main__':
    write_catalog()
    if arg('--catalog-only'):
        sys.exit(0)
    rows = []
    for t, e in REG.items():
        if only and t not in only:
            continue
        for v, params in e['variants'].items():
            if only_variant and v not in only_variant:
                continue
            out = os.path.join(ROOT, 'hd', 'models', t, f'{v}.glb')
            if skip_existing and os.path.exists(out):
                continue
            t0 = time.time()
            try:
                size = build_one(t, v, params)
                rows.append((t, v, size, time.time() - t0, ''))
                print(f'HDBUILD ok  {t}/{v}  {size / 1024:.0f} KB  {time.time() - t0:.1f}s', flush=True)
            except Exception as ex:
                traceback.print_exc()
                if os.path.exists(out) and not check_only:
                    os.remove(out)  # never leave a stale/broken model listed
                rows.append((t, v, 0, time.time() - t0, str(ex)))
                print(f'HDBUILD ERR {t}/{v}  {ex}', flush=True)
    write_catalog()
    total = sum(r[2] for r in rows)
    print(f'HDBUILD done: {sum(1 for r in rows if not r[4])}/{len(rows)} built, {total / 1048576:.1f} MB', flush=True)
